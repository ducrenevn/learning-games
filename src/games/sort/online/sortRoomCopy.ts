export type SortRoomCopyKey = keyof typeof sortRoomCopy.en;

export function sortRoomText(locale: Locale, key: SortRoomCopyKey, values?: Record<string, string | number>): string {
  let text: string = sortRoomCopy[locale][key] ?? sortRoomCopy.en[key] ?? key;
  for (const [k, v] of Object.entries(values ?? {})) {
    text = text.replaceAll('{' + k + '}', String(v));
  }
  return text;
}

export function sortRoomError(locale: Locale, key: string): string {
  if (key in sortErrorCopy[locale]) {
    return sortErrorCopy[locale][key as keyof typeof sortErrorCopy.en];
  }
  return sortErrorCopy[locale].SORT_SERVER_ERROR;
}

